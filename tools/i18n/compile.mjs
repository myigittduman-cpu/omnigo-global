import fs from 'node:fs/promises';
import path from 'node:path';
const folder='verification/localization-20261025';
const source=JSON.parse(await fs.readFile(`${folder}/catalog-source.json`,'utf8'));
const catalog={},covered=new Set(),errors=[];
const slots=text=>[...text.matchAll(/\{\d+\}/g)].map(m=>m[0]).sort().join('|');
for(const file of await fs.readdir('tools/i18n/translations')){
 if(!file.endsWith('.json'))continue;
 for(const [id,en,de]of JSON.parse(await fs.readFile(path.join('tools/i18n/translations',file),'utf8'))){
  if(!source[id]){errors.push(`Unknown message ${id}`);continue;}
  const key=source[id].source;
  if(covered.has(id))errors.push(`Duplicate message ${id}`);
  if([en,de].some(text=>!text||slots(text)!==slots(key)))errors.push(`Invalid placeholders: ${id}`);
  catalog[key]={en,de};covered.add(id);
 }
}
if(errors.length)throw new Error(errors.join('\n'));
const missing=source.map((r,id)=>({id,...r})).filter(r=>!covered.has(r.id));
await fs.writeFile('public/locales/catalog.js','// Generated by tools/i18n/compile.mjs from reviewed source-owned messages.\nexport const catalog=Object.freeze('+JSON.stringify(catalog,null,1)+');\n');
await fs.writeFile(`${folder}/coverage.json`,JSON.stringify({total:source.length,translated:covered.size,missing},null,2));
console.log(JSON.stringify({total:source.length,translated:covered.size,missing:missing.length}));
if(process.argv.includes('--complete')&&missing.length)process.exitCode=1;

<?php
declare(strict_types=1);
require dirname(__DIR__).'/bootstrap.php';
use Omnigo\{CustomerServiceNotifications,Database,DeliveryCipher,FileCenterSchema,InventoryAlerts,InventoryCatalog,InventoryProgress,InventorySchema,InventoryVisibility,NotificationSchema,PaymentDeletion,PushSchema,Repository,SupportRepository,SupportSchema,TableCatalogReplay};

function check(bool $ok,string $message): void {if (!$ok) throw new RuntimeException($message);}
$db=new Database(['dsn'=>'sqlite::memory:']);
$db->pdo->exec(file_get_contents(__DIR__.'/schema.sqlite.sql'));
InventorySchema::install($db);
SupportSchema::migrate($db);
NotificationSchema::migrate($db);
PushSchema::install($db);
FileCenterSchema::install($db);
$repository=new Repository($db);
$company=$repository->createCompany('Birinci');
$other=$repository->createCompany('İkinci');
$db->run("INSERT INTO users VALUES(1,'admin@example.invalid','Yönetici','x','admin',NULL),(2,'store@example.invalid','Mağaza','x','client',?)",[$company]);
$admin=$db->one('SELECT * FROM users WHERE id=1');
$client=$db->one('SELECT * FROM users WHERE id=2');
$inventory=new InventoryCatalog($db);
$progress=new InventoryProgress($db);
$cipher=DeliveryCipher::withKey(random_bytes(32));
$alerts=new InventoryAlerts($db,$cipher);
$listing=['id'=>'sku-source','sku'=>'ABC1','title'=>'Ürün','saleActive'=>true];
$rows=function(int $tenant)use($db) {
    return array_map(static fn($r)=>['type'=>$r['event_type'],...json_decode($r['payload'],true)],$db->all('SELECT payload,event_type FROM order_notifications WHERE company_id=? ORDER BY id',[$tenant]));
};
$key=$inventory->ingest($company,'n11',[...$listing,'quantity'=>3]);
$progress->ensure($company,'n11');
$db->run("UPDATE inventory_catalog_jobs SET last_success=? WHERE company_id=? AND provider='n11'",[gmdate('c'),$company]);
check($alerts->publish($company)===0,'İlk gözlem yeniden stok gelişi değildir');
$feed=static fn(int $qty)=>$inventory->ingest($company,'n11',[...$listing,'quantity'=>$qty]);
$feed(0);
check($alerts->publish($company)===1 && $alerts->publish($company)===0,'Tükenen stok bir kez yayınlanır');
$feed(6);
$db->run("UPDATE inventory_catalog_jobs SET error='Kaynak bekliyor' WHERE company_id=? AND provider='n11'",[$company]);
check($alerts->publish($company)===0,'Kaynak doğrulanmadan stok gelişi yayınlanamaz');
$db->run("UPDATE inventory_catalog_jobs SET error=NULL WHERE company_id=? AND provider='n11'",[$company]);
check($alerts->publish($company)===1 && $alerts->publish($company)===0,'Güncel kaynağın yeniden pozitif stoğu bir kez yayınlanır');
$events=$rows($company);
check(array_column($events,'events')===[['inventory_low'],['inventory_restocked']] && array_column($events,'audience')===['admin','admin'],'Gerçek geçiş ve yöneticiye özel zarf');
$vis=new InventoryVisibility($db);
$ver=fn()=>(int)$db->one('SELECT version FROM inventory_products WHERE company_id=? AND product_key=?',[$company,$key])['version'];
$vis->change($company,['productKey'=>$key,'action'=>'remove','version'=>$ver()],1);
$vis->change($company,['productKey'=>$key,'action'=>'restore','version'=>$ver()],1);
check($alerts->publish($company)===0,'Görünürlük geri alma bir stok hareketi değildir');
$vis->change($company,['productKey'=>$key,'action'=>'remove','version'=>$ver()],1);
$db->run('UPDATE inventory_removed_products SET removed_at=? WHERE company_id=?',[gmdate('c',time()-60),$company]);
$db->transaction(fn()=>TableCatalogReplay::restore($db,$company,'inventory',$key,time()));
check($alerts->publish($company)===0,'Tam kaynak aktarımında listeye geri dönen satır da başlangıç gözlemidir');
$feed(0);$alerts->publish($company);$feed(4);$alerts->publish($company);
check(count($rows($company))===4,'Elle geri alma sonrası sonraki gerçek stok döngüsü yeni iki olay üretir');
$support=new SupportRepository($db);
$input=['subject'=>'Ürün','category'=>'issue','body'=>'Özel bildirim metnine girmemeli','requestId'=>str_repeat('a',48)];
$ticket=$support->create($client,$company,$input);
$support->create($client,$company,$input);
$support->status($admin,$company,$ticket,'closed');
$support->status($admin,$company,$ticket,'closed');
$support->create($admin,$company,[...$input,'requestId'=>str_repeat('b',48)]);
$notices=array_slice($rows($company),4);
check(array_column($notices,'type')===['support','user','resolved','user'],'Talep oluşturma ve kapatmada her alıcıya bir olay');
check(array_column($notices,'audience')===['admin','admin','client','admin'] && $notices[2]['recipientId']===2,'Yönetici olayları ayrı, müşteri çözümü talep sahibine özeldir');
check(!str_contains(json_encode($notices,JSON_UNESCAPED_UNICODE),'Özel bildirim'),'Mesaj içeriği genel zarf dışında kalır');
$payment=['channel'=>'n11','expectedDate'=>'2026-11-29','expectedCents'=>1000,'status'=>'pending','source'=>'Elle giriş'];
$saved=$repository->save($admin,$company,'payments',$payment,null);
$audit=$db->one("SELECT id FROM audit WHERE company_id=? AND record_id=? AND action='Eklendi' ORDER BY id DESC",[$company,$saved['id']]);
$db->transaction(fn()=>CustomerServiceNotifications::payment($db,$admin,$company,$saved['id'],(int)$audit['id'],false));
$amended=$repository->save($admin,$company,'payments',[...$payment,'expectedCents'=>1500,'version'=>$saved['version']],$saved['id']);
(new PaymentDeletion($db))->delete($admin,$company,$saved['id'],['version'=>$amended['version']]);
$paymentEvents=array_values(array_filter($rows($company),fn($event)=>in_array('payment_updated',$event['events']??[],true)));
check(array_column($paymentEvents,'operation')===['created','created','updated','updated','deleted','deleted'],'Hakedişin kayıt, düzeltme, silme ve tekrar akışı');
check(array_count_values(array_column($paymentEvents,'audience'))===['client'=>3,'admin'=>3],'Her hakediş işlemi her alıcı kapsamına tam bir zarf verir');
check($rows($other)===[],'Aynı sistemde diğer mağazaya hiçbir işlem yazılmaz');
echo "Stok geçişleri, yeniden listeleme, destek açma/kapatma ve hakediş ekle/düzelt/sil ana işlem yollarında doğrulandı.\n";
